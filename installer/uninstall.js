// ------------------------------------------------------------------
// Execution
// ------------------------------------------------------------------
async function applyPlan(plan, ctx) {
  const { targetDir } = ctx;
  const result = {
    removed: [], edited: [], failed: [], skipped: [], removedDirs: [],
    backups: [], workBackups: []
  };

  /**
   * Copy a file into .toh-uninstall-backup/ before it is touched. Used for the
   * user's own work AND for every file we could only match by name: without an
   * install record there is no way to know whether the user edited it, and an
   * edit the user cannot get back is the one outcome this command must never
   * produce. A failed backup cancels that file's deletion.
   */
  const backup = async (item, bucket) => {
    try {
      const dest = join(absOf(targetDir, ctx.backupDirName), ...item.rel.split('/'));
      await fs.ensureDir(dirname(dest));
      await fs.copy(absOf(targetDir, item.rel), dest, { overwrite: true, errorOnExist: false });
      bucket.push(item.rel);
      return true;
    } catch (err) {
      result.failed.push({
        rel: item.rel,
        why: `could not save a backup copy (${err.message}) — so I did not touch it`
      });
      item.skip = true;
      return false;
    }
  };

  // 1. Back up the user's live work before deleting it.
  for (const item of plan.userWork) await backup(item, result.workBackups);

  // 2. Back up every unverified (name-matched) file and edit.
  for (const item of plan.removals) {
    if (!item.backup) continue;
    if (!(await isRealFile(targetDir, item.rel))) continue;
    await backup(item, result.backups);
  }
  for (const edit of plan.edits) {
    if (!edit.backup) continue;
    if (!(await isRealFile(targetDir, edit.rel))) continue;
    await backup(edit, result.backups);
  }

  // 3. Plain file removals (+ the user work the backup step protected).
  for (const item of [...plan.removals.filter((i) => !i.skip), ...plan.userWork.filter((i) => !i.skip)]) {
    if (!(await pathIsSafe(targetDir, item.rel))) {
      result.skipped.push({ rel: item.rel, why: 'the path became a shortcut (symlink) — skipped for safety' });
      continue;
    }
    if (!(await isRealFile(targetDir, item.rel))) continue; // already gone: idempotent
    try {
      await fs.unlink(absOf(targetDir, item.rel));
      result.removed.push(item.rel);
    } catch (err) {
      result.failed.push({ rel: item.rel, why: err.message });
    }
  }

  // 4. Surgical edits — re-verified against what we previewed.
  for (const edit of plan.edits) {
    if (edit.skip) continue; // its backup failed: leave the file exactly as it is
    if (!(await pathIsSafe(targetDir, edit.rel))) {
      result.skipped.push({ rel: edit.rel, why: 'the path became a shortcut (symlink) — skipped for safety' });
      continue;
    }
    if (!(await isRealFile(targetDir, edit.rel))) continue;
    try {
      const nowSha = await shaOfFile(targetDir, edit.rel);
      if (edit.expectedSha && nowSha !== edit.expectedSha) {
        result.skipped.push({ rel: edit.rel, why: 'the file changed while I was asking you — I left it alone' });
        continue;
      }
      const abs = absOf(targetDir, edit.rel);
      if (edit.kind === 'delete') {
        await fs.unlink(abs);
        result.removed.push(edit.rel);
      } else if (edit.kind === 'truncate') {
        await fs.truncate(abs, edit.bytes);
        result.edited.push({ rel: edit.rel, summary: edit.summary });
      } else {
        await fs.writeFile(abs, edit.content);
        result.edited.push({ rel: edit.rel, summary: edit.summary });
      }
    } catch (err) {
      result.failed.push({ rel: edit.rel, why: err.message });
    }
  }

  // 5. Directories: deepest first, only when empty.
  const dirs = [...plan.dirs].sort((a, b) => b.split('/').length - a.split('/').length || (a < b ? 1 : -1));
  for (const rel of dirs) {
    if (!rel || rel === '.') continue;
    if (!(await pathIsSafe(targetDir, rel))) continue;
    if (!(await isRealDir(targetDir, rel))) continue;
    try {
      const entries = await fs.readdir(absOf(targetDir, rel));
      if (entries.length === 0) {
        await fs.rmdir(absOf(targetDir, rel));
        result.removedDirs.push(rel);
      }
    } catch (err) {
      result.failed.push({ rel, why: `could not tidy up the folder (${err.message})` });
    }
  }

  return result;
}

/**
 * The manifest goes LAST. If anything of ours is still on disk (a file you
 * edited, a failure), we keep a trimmed record so a second `toh uninstall` can
 * finish the job instead of guessing.
 */
async function finalizeManifest(ctx, plan, result) {
  const { targetDir } = ctx;
  const rel = '.toh/manifest.json';
  if (!(await isRealFile(targetDir, rel))) return null;

  const leftovers = [
    ...plan.keeps.filter((k) => !isLiveState(k.rel) && !k.rel.endsWith('/')).map((k) => k.rel),
    ...plan.warnings.map((w) => w.rel),
    ...result.failed.map((f) => f.rel),
    ...result.skipped.map((s) => s.rel)
  ];
  const stillOurs = [];
  for (const p of new Set(leftovers)) {
    if (ctx.manifestFiles.has(p) && (await isRealFile(targetDir, p))) stillOurs.push(p);
  }

  if (stillOurs.length === 0 && result.failed.length === 0) {
    try {
      await fs.unlink(absOf(targetDir, rel));
      result.removed.push(rel);
    } catch (err) {
      result.failed.push({ rel, why: err.message });
    }
    // .toh may now be empty (nothing kept) — try one last tidy-up.
    for (const d of ['.toh/memory/archive', '.toh/memory', '.toh']) {
      if (!(await isRealDir(targetDir, d))) continue;
      try {
        if ((await fs.readdir(absOf(targetDir, d))).length === 0) {
          await fs.rmdir(absOf(targetDir, d));
          result.removedDirs.push(d);
        }
      } catch { /* leave it */ }
    }
    return null;
  }

  try {
    const manifest = await fs.readJson(absOf(targetDir, rel));
    manifest.files = (manifest.files || []).filter((f) => stillOurs.includes(f.path));
    manifest.uninstallPartial = true;
    manifest.uninstalledAt = new Date().toISOString();
    await fs.writeJson(absOf(targetDir, rel), manifest, { spaces: 2 });
    return stillOurs.length;
  } catch {
    return stillOurs.length;
  }
}

