const sha256 = (buf) => crypto.createHash('sha256').update(buf).digest('hex');

function absOf(targetDir, rel) {
  return join(targetDir, ...rel.split('/'));
}

/**
 * Refuse any path that leaves the project or crosses a symlink.
 * Verified hazard: with .claude/skills symlinked elsewhere, deleting a "known"
 * child path empties a directory outside the project.
 */
async function pathIsSafe(targetDir, rel) {
  const parts = rel.split('/');
  if (parts.some((p) => p === '' || p === '.' || p === '..')) return false;
  let cur = targetDir;
  for (const part of parts) {
    cur = join(cur, part);
    let st;
    try {
      st = await fs.lstat(cur);
    } catch {
      return true; // does not exist -> nothing to traverse, nothing to delete
    }
    if (st.isSymbolicLink()) return false;
  }
  return true;
}

async function isRealFile(targetDir, rel) {
  try {
    const st = await fs.lstat(absOf(targetDir, rel));
    return st.isFile();
  } catch {
    return false;
  }
}

async function isRealDir(targetDir, rel) {
  try {
    const st = await fs.lstat(absOf(targetDir, rel));
    return st.isDirectory();
  } catch {
    return false;
  }
}

async function readText(targetDir, rel) {
  return fs.readFile(absOf(targetDir, rel), 'utf8');
}

async function shaOfFile(targetDir, rel) {
  return sha256(await fs.readFile(absOf(targetDir, rel)));
}

async function listFilesRecursive(dir, prefix = '') {
  const out = [];
  let entries;
  try {
    entries = await fs.readdir(dir, { withFileTypes: true });
  } catch {
    return out;
  }
  for (const entry of entries.sort((a, b) => (a.name < b.name ? -1 : 1))) {
    if (entry.isSymbolicLink()) continue;
    const rel = prefix ? `${prefix}/${entry.name}` : entry.name;
    if (entry.isDirectory()) out.push(...(await listFilesRecursive(join(dir, entry.name), rel)));
    else if (entry.isFile()) out.push(rel);
  }
  return out;
}

function plural(n, one, many) {
  return `${n} ${n === 1 ? one : many}`;
}

