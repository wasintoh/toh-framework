function newPlan() {
  return {
    removals: [],   // { rel, group, verified }
    edits: [],      // { rel, group, kind, summary, expectedSha, apply-data }
    keeps: [],      // { rel, group, why }        (yours / kept on purpose)
    warnings: [],   // { rel, why }               (left alone, needs a human)
    userWork: [],   // { rel, group }             (deleted only when asked for)
    liveWork: [],   // { rel, group }             (plan/ledger/notes found on disk)
    liveDirs: [],   // 'toh/memory'-style dirs holding live work
    backups: [],    // { rel, to }
    dirs: new Set() // candidate directories to remove when empty
  };
}

/**
 * Promote the user's live work (plan, ledger, notes) onto the delete list.
 * Called for --all, and for a "yes" to the second question in an interactive
 * run — so the choice exists even for someone who never heard of the flag.
 */
function adoptUserWork(plan) {
  plan.keeps = plan.keeps.filter((k) => !k.liveState);
  for (const item of plan.liveWork) {
    if (plan.userWork.some((u) => u.rel === item.rel)) continue;
    plan.userWork.push({ rel: item.rel, group: item.group });
    markDirs(plan, item.rel);
  }
  for (const d of plan.liveDirs) {
    plan.dirs.add(d);
    plan.dirs.add(`${d}/archive`);
  }
}

function markDirs(plan, rel) {
  const parts = rel.split('/');
  parts.pop();
  while (parts.length) {
    plan.dirs.add(parts.join('/'));
    parts.pop();
  }
}

function isLiveState(rel) {
  return LIVE_STATE_FILES.includes(rel) || LIVE_STATE_DIRS.some((d) => rel.startsWith(d));
}

async function buildPlan(ctx) {
  const { targetDir, cat, manifestFiles, hasInventory } = ctx;
  const plan = newPlan();
  const seen = new Set();

  // --- candidate paths: known names + everything the install recorded -------
  const candidates = [];
  for (const rel of derivedPaths(cat)) {
    if (seen.has(rel)) continue;
    seen.add(rel);
    candidates.push({ rel, fromManifest: manifestFiles.has(rel) });
  }
  for (const rel of manifestFiles.keys()) {
    if (seen.has(rel)) continue;
    seen.add(rel);
    candidates.push({ rel, fromManifest: true });
  }
  // Alias command files are data-derived (generated from `aliases:` frontmatter
  // with collision skips) — identify them by their generated body, never by a
  // toh-*.md glob: the user may legitimately author .claude/commands/toh-mine.md.
  if (await isRealDir(targetDir, '.claude/commands')) {
    for (const f of await listFilesRecursive(absOf(targetDir, '.claude/commands'))) {
      const rel = `.claude/commands/${f}`;
      if (seen.has(rel) || !f.endsWith('.md')) continue;
      try {
        if ((await readText(targetDir, rel)).includes(ALIAS_SIGNATURE)) {
          seen.add(rel);
          candidates.push({ rel, fromManifest: manifestFiles.has(rel), aliasFile: true });
        }
      } catch { /* unreadable -> leave it */ }
    }
  }

  // --- classify -------------------------------------------------------------
  for (const cand of candidates.sort((a, b) => (a.rel < b.rel ? -1 : 1))) {
    const { rel } = cand;
    if (CO_OWNED.has(rel)) continue;              // dedicated strategies below
    if (rel === '.toh/manifest.json') continue;   // removed last, on its own
    if (!(await isRealFile(targetDir, rel))) continue;
    if (!(await pathIsSafe(targetDir, rel))) {
      plan.warnings.push({
        rel,
        why: 'this path goes through a shortcut (symlink), so it may point outside your project — I left it alone'
      });
      continue;
    }

    const group = groupOf(rel);

    if (isLiveState(rel)) continue; // handled as one block by planLiveState()

    const record = manifestFiles.get(rel);
    if (record && record.sha256) {
      const actual = await shaOfFile(targetDir, rel);
      if (actual === record.sha256) {
        plan.removals.push({ rel, group, verified: true });
        markDirs(plan, rel);
      } else {
        plan.keeps.push({ rel, group, why: 'you (or a tool) changed this file after it was installed' });
      }
      continue;
    }

    if (hasInventory) {
      // A complete install record exists and does not list this file: it is not
      // ours to delete. Leave it and say where it is.
      plan.warnings.push({ rel, why: 'not in the install record, so I could not confirm it is mine — I left it' });
      continue;
    }

    // No usable install record: fall back to name-scoped removal. The name says
    // the file is ours, but nothing proves the user did not edit it after the
    // install — so a copy goes into the backup folder before it is deleted.
    plan.removals.push({ rel, group, verified: false, backup: true });
    markDirs(plan, rel);
  }

  // --- co-owned files, one strategy each ------------------------------------
  await planClaudeMd(ctx, plan);
  await planMarkerBlock(ctx, plan, 'AGENTS.md');
  await planStopHook(ctx, plan, '.claude/settings.json', 'the Toh "keep going" reminder');
  await planStopHook(ctx, plan, '.agents/hooks.json', 'the Toh "keep going" reminder');
  await planStampedFile(ctx, plan, '.claude/loop.md', TFW_LOOP_MARKER, 'first line');
  await planStampedFile(ctx, plan, '.codex/config.toml', CODEX_CONFIG_STAMP, 'first line');
  await planHashOnlyFile(ctx, plan, '.cursorrules');
  await planHashOnlyFile(ctx, plan, '.gemini/settings.json');
  await planGeminiMd(ctx, plan);

  // --- the user's live work: plan, ledger, both memory folders --------------
  await planLiveState(ctx, plan);

  // Directories the installer created (hint only — emptiness still decides).
  for (const root of SURFACE_ROOTS) plan.dirs.add(root);
  for (const d of ctx.dirsCreated) plan.dirs.add(d);

  return plan;
}

/**
 * .toh/plan.md, .toh/progress.md, .toh/memory/, .claude/memory/ — the user's
 * live work. The installer seeds them; the agents fill them with the project's
 * real plan, ledger and decision history. Kept by default, always.
 */
async function planLiveState(ctx, plan) {
  const { targetDir, includeUserWork } = ctx;

  for (const rel of LIVE_STATE_FILES) {
    if (!(await isRealFile(targetDir, rel))) continue;
    if (!(await pathIsSafe(targetDir, rel))) continue;
    const group = groupOf(rel);
    const label = rel.endsWith('plan.md')
      ? 'your project plan — what the AI is building and what is already ticked off'
      : 'your work log — the record of what has been done so far';
    plan.liveWork.push({ rel, group });
    plan.keeps.push({ rel, group, why: label, liveState: true });
  }

  for (const dir of LIVE_STATE_DIRS) {
    const relDir = dir.replace(/\/$/, '');
    if (!(await isRealDir(targetDir, relDir))) continue;
    const files = await listFilesRecursive(absOf(targetDir, relDir));
    for (const f of files) {
      const rel = `${relDir}/${f}`;
      if (!(await pathIsSafe(targetDir, rel))) continue;
      plan.liveWork.push({ rel, group: groupOf(rel) });
    }
    plan.liveDirs.push(relDir);
    plan.keeps.push({
      rel: `${relDir}/`,
      group: groupOf(relDir),
      liveState: true,
      why: `project notes the AI keeps for you — decisions, architecture, history (${plural(files.length, 'file', 'files')})`
    });
  }

  if (includeUserWork) adoptUserWork(plan);
}

/**
 * CLAUDE.md — the highest-risk file: the installer appends ~455 lines with NO
 * markers at all. The only safe removals are byte-exact ones, which need the
 * manifest (it records the file's sha256 after install and, when we appended to
 * a file the user already had, the exact byte length of their original text).
 * Anything else: leave the file and tell the user where our section starts.
 */
/**
 * Where our own generated text sits inside a CLAUDE.md that has no markers
 * (every install before v2.1 wrote one). Returns { start, end, exact } or null.
 *
 * Two levels of evidence, both anchored on text this package can regenerate:
 *   exact  — our current generated block appears verbatim: provable, no backup
 *            needed.
 *   shaped — the file was written by an older version, so byte-equality fails:
 *            the block still has to start with our H1 line, end with our last
 *            line, and contain most of our section headings. Removal is offered
 *            but flagged unverified, and a copy is always saved first.
 */
function locateClaudeMdBlock(text) {
  for (const lang of ['en', 'th']) {
    const gen = generateClaudeMd(lang);
    const idx = text.indexOf(gen);
    if (idx >= 0) return { start: idx, end: idx + gen.length, exact: true };
  }

  const gen = generateClaudeMd('en');
  const genLines = gen.split('\n').map((l) => l.trim()).filter(Boolean);
  const headings = [...new Set(genLines.filter((l) => /^#{1,3} \S/.test(l)))];
  if (genLines.length === 0 || headings.length < 8) return null;
  const firstLine = genLines[0];
  const lastLine = genLines[genLines.length - 1];

  const startsAtLine = (i) => i === 0 || text[i - 1] === '\n';
  let start = -1;
  for (let i = text.indexOf(firstLine); i >= 0; i = text.indexOf(firstLine, i + 1)) {
    if (startsAtLine(i)) { start = i; break; }
  }
  if (start < 0) return null;

  const endAnchor = text.lastIndexOf(lastLine);
  if (endAnchor <= start) return null;
  let end = endAnchor + lastLine.length;
  if (text[end] === '\r') end += 1;
  if (text[end] === '\n') end += 1;

  const block = text.slice(start, end);
  const found = headings.filter((h) => block.includes(h)).length;
  if (found / headings.length < 0.6) return null;

  return { start, end, exact: false };
}

async function planClaudeMd(ctx, plan) {
  const { targetDir, manifestFiles } = ctx;
  const rel = 'CLAUDE.md';
  if (!(await isRealFile(targetDir, rel))) return;
  if (!(await pathIsSafe(targetDir, rel))) {
    plan.warnings.push({ rel, why: 'this path is a shortcut (symlink) — I left it alone' });
    return;
  }

  const buf = await fs.readFile(absOf(targetDir, rel));
  const sha = sha256(buf);
  const record = manifestFiles.get(rel);
  const mentionsUs = buf.includes('Toh Framework');

  // Installed by v2.1 or later: our section is delimited, so the generic
  // marker-block strategy lifts out exactly our part and nothing else.
  const asText = buf.toString('utf8');
  if (asText.includes(TOH_BLOCK_START) || asText.includes(TOH_BLOCK_END)) {
    await planMarkerBlock(ctx, plan, rel);
    return;
  }

  if (record && record.sha256 === sha) {
    if (!record.preexisted) {
      plan.edits.push({
        rel,
        group: 'claude',
        kind: 'delete',
        expectedSha: sha,
        summary: 'delete it — the whole file was written by Toh Framework'
      });
      markDirs(plan, rel);
      return;
    }
    if (typeof record.preexistedBytes === 'number' && record.preexistedSha256) {
      const prefix = buf.subarray(0, record.preexistedBytes);
      if (prefix.length === record.preexistedBytes && sha256(prefix) === record.preexistedSha256) {
        plan.edits.push({
          rel,
          group: 'claude',
          kind: 'truncate',
          bytes: record.preexistedBytes,
          expectedSha: sha,
          summary: 'take out the Toh section and put your own CLAUDE.md back exactly as it was'
        });
        return;
      }
    }
  }

  // No markers and no matching record — an older install, or the file was
  // edited since. Recognise our own text instead of asking the user to do it.
  const located = mentionsUs ? locateClaudeMdBlock(asText) : null;
  if (located) {
    const before = asText.slice(0, located.start);
    const after = asText.slice(located.end);
    const backup = !located.exact;
    if (before.trim() === '' && after.trim() === '') {
      plan.edits.push({
        rel,
        group: 'claude',
        kind: 'delete',
        expectedSha: sha,
        backup,
        summary: 'delete it — every line in it was written by Toh Framework'
      });
      markDirs(plan, rel);
      return;
    }
    let out = before.replace(/\n\n$/, '') + after;
    if (before.trim() === '') out = out.replace(/^\n+/, '');
    plan.edits.push({
      rel,
      group: 'claude',
      kind: 'write',
      content: out,
      expectedSha: sha,
      backup,
      summary: 'take out the Toh Framework section — everything you wrote in this file stays'
    });
    return;
  }

  if (mentionsUs) {
    const idx = asText.indexOf('# Toh Framework');
    const where = idx >= 0
      ? ` If you want to check, the words "# Toh Framework" appear at line ${asText.slice(0, idx).split('\n').length}.`
      : '';
    const because = record
      ? 'it no longer matches what was installed, so it has been edited since'
      : 'my install record does not list this file';
    plan.warnings.push({
      rel,
      why:
        'this file mentions Toh Framework, but none of it matches the text I write, and ' +
        `${because} — so I could not tell which part (if any) is mine, and I left the file exactly as it is.` +
        `${where} Read it yourself and delete anything of mine you do not want.`
    });
  } else {
    plan.keeps.push({ rel, group: 'claude', why: 'nothing of ours is in it' });
  }
}

/** AGENTS.md — properly delimited, so this works with or without a manifest. */
async function planMarkerBlock(ctx, plan, rel) {
  const { targetDir, manifestFiles } = ctx;
  if (!(await isRealFile(targetDir, rel))) return;
  if (!(await pathIsSafe(targetDir, rel))) {
    plan.warnings.push({ rel, why: 'this path is a shortcut (symlink) — I left it alone' });
    return;
  }

  let text;
  try {
    text = await readText(targetDir, rel);
  } catch (err) {
    plan.warnings.push({ rel, why: `I could not read it (${err.message}) — I left it alone` });
    return;
  }

  const starts = text.split(TOH_BLOCK_START).length - 1;
  const ends = text.split(TOH_BLOCK_END).length - 1;
  if (starts === 0 && ends === 0) {
    plan.keeps.push({ rel, group: groupOf(rel), why: 'nothing of ours is in it' });
    return;
  }
  if (starts !== 1 || ends !== 1) {
    plan.warnings.push({
      rel,
      why: `I found ${starts} start and ${ends} end markers instead of one of each, so I could not tell exactly which part is mine — I left the file alone`
    });
    return;
  }

  const start = text.indexOf(TOH_BLOCK_START);
  const end = text.indexOf(TOH_BLOCK_END, start);
  if (end < 0) {
    plan.warnings.push({ rel, why: 'the end marker comes before the start marker — I left the file alone' });
    return;
  }

  // Lazy, first-START to first-following-END. (The installer's own regex is
  // greedy; copying it would eat user text between two quoted markers.)
  const head = text.slice(0, start).replace(/\n\n$/, '');
  const tail = text.slice(end + TOH_BLOCK_END.length);
  let out = head + tail;
  if (head === '') out = out.replace(/^\n+/, '');

  const record = manifestFiles.get(rel);
  const sha = await shaOfFile(targetDir, rel);

  // Byte-exact restore when our block ends the file and nothing changed since.
  if (
    record &&
    record.sha256 === sha &&
    record.preexisted &&
    typeof record.preexistedBytes === 'number' &&
    record.preexistedSha256 &&
    tail.trim() === ''
  ) {
    const buf = await fs.readFile(absOf(targetDir, rel));
    const prefix = buf.subarray(0, record.preexistedBytes);
    if (prefix.length === record.preexistedBytes && sha256(prefix) === record.preexistedSha256) {
      plan.edits.push({
        rel,
        group: groupOf(rel),
        kind: 'truncate',
        bytes: record.preexistedBytes,
        expectedSha: sha,
        summary: 'take out the Toh section and put your own file back exactly as it was'
      });
      return;
    }
  }

  if (out.trim() === '') {
    plan.edits.push({
      rel,
      group: groupOf(rel),
      kind: 'delete',
      expectedSha: sha,
      summary: 'delete it — it contains nothing but the Toh section'
    });
    markDirs(plan, rel);
    return;
  }

  plan.edits.push({
    rel,
    group: groupOf(rel),
    kind: 'write',
    content: out,
    expectedSha: sha,
    summary: 'take out only the Toh section between its markers — everything you wrote stays'
  });
}

/** .claude/settings.json + .agents/hooks.json — remove ONLY our Stop entry. */
async function planStopHook(ctx, plan, rel, label) {
  const { targetDir, manifestFiles } = ctx;
  if (!(await isRealFile(targetDir, rel))) return;
  if (!(await pathIsSafe(targetDir, rel))) {
    plan.warnings.push({ rel, why: 'this path is a shortcut (symlink) — I left it alone' });
    return;
  }

  let raw;
  try {
    raw = await readText(targetDir, rel);
  } catch (err) {
    plan.warnings.push({ rel, why: `I could not read it (${err.message}) — I left it alone` });
    return;
  }
  if (!raw.includes(TFW_STOP_HOOK_MARKER)) {
    plan.keeps.push({ rel, group: groupOf(rel), why: 'nothing of ours is in it' });
    return;
  }

  let obj;
  try {
    obj = JSON.parse(raw);
  } catch (err) {
    plan.warnings.push({
      rel,
      why: `this file is not valid JSON (${err.message}), so editing it safely is impossible — I left it alone`
    });
    return;
  }
  if (obj === null || typeof obj !== 'object' || Array.isArray(obj)) {
    plan.warnings.push({ rel, why: 'this file does not look like the settings file I expected — I left it alone' });
    return;
  }

  const hooks = obj.hooks;
  const stop = hooks && typeof hooks === 'object' && !Array.isArray(hooks) ? hooks.Stop : undefined;
  if (!Array.isArray(stop)) {
    plan.warnings.push({ rel, why: 'the Toh reminder is not where I expected it — I left this file alone' });
    return;
  }

  const kept = stop.filter((entry) => {
    try {
      return !JSON.stringify(entry === undefined ? null : entry).includes(TFW_STOP_HOOK_MARKER);
    } catch {
      return true; // unserializable -> not ours -> keep
    }
  });
  const removed = stop.length - kept.length;
  if (removed === 0) {
    plan.keeps.push({ rel, group: groupOf(rel), why: 'nothing of ours is in it' });
    return;
  }

  if (kept.length > 0) hooks.Stop = kept;
  else delete hooks.Stop;
  if (Object.keys(hooks).length === 0) delete obj.hooks;

  // Whole-file deletion needs the file to hold nothing but our hook. When the
  // install record knows the file, it decides; with no record at all, an empty
  // leftover object proves the point on its own — the user cannot have authored
  // a settings file whose entire content was our marker.
  const record = manifestFiles.get(rel);
  const weCreatedIt = record ? !record.preexisted : true;
  const sha = await shaOfFile(targetDir, rel);

  if (Object.keys(obj).length === 0 && weCreatedIt) {
    plan.edits.push({
      rel,
      group: groupOf(rel),
      kind: 'delete',
      expectedSha: sha,
      summary: `delete it — it only ever held ${label}`
    });
    markDirs(plan, rel);
    return;
  }

  const othersNote = kept.length > 0
    ? `, keeping ${plural(kept.length, 'other setting of yours', 'other settings of yours')}`
    : '';
  plan.edits.push({
    rel,
    group: groupOf(rel),
    kind: 'write',
    content: `${JSON.stringify(obj, null, 2)}\n`,
    expectedSha: sha,
    summary: `remove ${label}${othersNote} — everything else in this file stays`
  });
}

