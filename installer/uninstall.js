/**
 * Toh Framework Uninstaller — `toh uninstall`
 *
 * The counterpart to `toh install`, written for someone who has no idea what
 * any of these files are. Three rules outrank everything else here:
 *
 *   1. Never delete or corrupt a file the user wrote. When ownership is not
 *      provable, LEAVE the file and say so.
 *   2. Files we share with the user (CLAUDE.md, AGENTS.md, .claude/settings.json,
 *      .agents/hooks.json, ...) are edited SURGICALLY — our marker block or our
 *      hook entry only, every other byte untouched. Our part missing or the file
 *      unreadable => warn and skip, never rewrite.
 *   3. .toh/plan.md, .toh/progress.md and both memory folders are the user's
 *      live work. They are KEPT unless the user explicitly asks for --all,
 *      and even then a copy is saved first.
 *
 * Ownership evidence, strongest first:
 *   a. .toh/manifest.json manifestSchema >= 2 — path + sha256 of every file the
 *      installer actually wrote, plus what a co-owned file looked like BEFORE
 *      the install. Hash match = ours and unmodified; mismatch = the user edited
 *      it, so we keep it.
 *   b. our own markers: <!-- TOH-FRAMEWORK-START/END --> (AGENTS.md),
 *      <TFW-STOP-HOOK> (both hook files), '<!-- generated by toh-framework -->'
 *      (.claude/loop.md), '# Generated by Toh Framework' (.codex/config.toml).
 *   c. known filenames derived from the running package's src/ — used only when
 *      there is no schema-2 manifest (old, missing or corrupt), and reported as
 *      "could not verify".
 *
 * Directories are removed only when they are empty afterwards. The target
 * directory itself is NEVER removed.
 */

