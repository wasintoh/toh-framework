async function buildCatalog(srcDir) {
  const cat = {
    ok: false,
    skillFiles: [],       // relative to <root>/skills
    skillDirs: [],
    agentFiles: [],       // src/agents/*.md (+ README.md)
    agentNames: [],       // frontmatter names AND source filenames
    commandFiles: [],
    templateFiles: [],
    workflowFiles: [],
    geminiCommandFiles: [],
    agentsSkillDirs: []
  };
  if (!(await fs.pathExists(srcDir))) return cat;

  cat.skillFiles = await listFilesRecursive(join(srcDir, 'skills'));
  cat.skillDirs = [...new Set(cat.skillFiles.map((f) => f.split('/')[0]))];

  const agentDir = join(srcDir, 'agents');
  cat.agentFiles = (await listFilesRecursive(agentDir)).filter((f) => !f.includes('/'));
  const names = new Set();
  for (const file of cat.agentFiles) {
    if (!file.endsWith('.md') || file === 'README.md') continue;
    names.add(file); // copy-through fallback writes the source filename
    try {
      const raw = await fs.readFile(join(agentDir, file), 'utf8');
      const fm = raw.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n/);
      const parsed = fm ? yaml.load(fm[1]) : null;
      if (parsed && typeof parsed.name === 'string' && parsed.name.trim()) {
        names.add(`${parsed.name.trim()}.md`);
      }
    } catch {
      // Unparseable source: the filename entry above still covers it.
    }
  }
  cat.agentNames = [...names];

  cat.commandFiles = (await listFilesRecursive(join(srcDir, 'commands'))).filter((f) => !f.includes('/'));
  cat.templateFiles = await listFilesRecursive(join(srcDir, 'templates'));
  cat.workflowFiles = (await listFilesRecursive(join(srcDir, 'antigravity-workflows'))).filter((f) => f.endsWith('.md'));
  cat.geminiCommandFiles = (await listFilesRecursive(join(srcDir, 'gemini-commands'))).filter((f) => f.endsWith('.toml'));

  // .agents/skills = 23 skill wrappers + one command skill per TOML
  const commandSkillNames = cat.geminiCommandFiles.map((f) =>
    f === 'toh.toml' ? 'toh' : `toh-${f.replace(/^toh\//, '').replace(/\.toml$/, '')}`
  );
  cat.agentsSkillDirs = [...new Set([...cat.skillDirs, ...commandSkillNames])];
  // .agents/commands = one native slash command per TOML (ZCode reads these)
  cat.agentsCommandFiles = commandSkillNames.map((n) => `${n}.md`);

  cat.ok = cat.skillDirs.length > 0 && cat.commandFiles.length > 0;
  return cat;
}

/** Every path this package is known to write, by name (existence not checked). */
function derivedPaths(cat) {
  const out = [];
  const add = (p) => out.push(p);

  for (const f of cat.skillFiles) {
    add(`.toh/skills/${f}`);
    add(`.claude/skills/${f}`);
    add(`.gemini/skills/${f}`);
  }
  for (const f of cat.templateFiles) {
    add(`.toh/templates/${f}`);
    add(`.claude/templates/${f}`);
  }
  for (const f of cat.agentFiles) add(`.toh/agents/${f}`);
  for (const f of cat.commandFiles) {
    add(`.toh/commands/${f}`);
    add(`.claude/commands/${f}`);
  }
  for (const n of cat.agentNames) {
    add(`.claude/agents/${n}`);
    add(`.cursor/agents/${n}`);
    add(`.agents/agents/${n}`);
  }
  for (const d of cat.agentsSkillDirs) add(`.agents/skills/${d}/SKILL.md`);
  for (const f of cat.agentsCommandFiles) add(`.agents/commands/${f}`);
  // v2.2: native Codex agents + their ownership manifest
  for (const n of cat.agentNames) add(`.codex/agents/${n.replace(/\.md$/, '')}.toml`);
  add('.codex/toh-framework.json');
  for (const f of cat.workflowFiles) {
    add(`.agents/workflows/${f}`);
    add(`.agent/workflows/${f}`);
  }
  for (const f of cat.geminiCommandFiles) add(`.gemini/commands/${f}`);

  add('.toh/capabilities.json');
  add('.cursor/rules/toh-framework.mdc');
  add('.cursor/rules/toh-agents.mdc');
  add('.agents/rules/toh-framework.md');

  return out;
}

