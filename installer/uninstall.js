async function detectInstall(targetDir, cat) {
  const probes = [
    '.toh/manifest.json',
    '.toh/capabilities.json',
    '.toh/commands',
    '.toh/agents',
    '.toh/skills',
    '.toh/templates',
    // The live work a default uninstall deliberately KEEPS. Without these
    // probes a follow-up `--all` run would say "I did not find Toh Framework
    // here" and the kept files could never be removed with our own tool.
    '.toh/plan.md',
    '.toh/progress.md',
    '.toh/memory',
    '.cursor/rules/toh-framework.mdc',
    '.agents/rules/toh-framework.md',
    '.gemini/commands/toh.toml',
    '.agent/workflows'
  ];
  for (const p of probes) {
    if ((await isRealFile(targetDir, p)) || (await isRealDir(targetDir, p))) return true;
  }
  // .claude/memory alone counts only when it holds the memory set we seed —
  // a lone user-made .claude/memory/notes.md must never look like an install.
  if (
    (await isRealFile(targetDir, '.claude/memory/summary.md')) &&
    (await isRealFile(targetDir, '.claude/memory/agents-log.md'))
  ) return true;
  for (const d of cat.skillDirs.slice(0, 3)) {
    if (await isRealDir(targetDir, `.claude/skills/${d}`)) return true;
    if (await isRealDir(targetDir, `.agents/skills/${d}`)) return true;
  }
  // Marker-only leftovers (a partially installed tree with nothing else left)
  for (const [rel, marker] of [
    ['AGENTS.md', TOH_BLOCK_START],
    ['.claude/settings.json', TFW_STOP_HOOK_MARKER],
    ['.agents/hooks.json', TFW_STOP_HOOK_MARKER],
    ['.claude/loop.md', TFW_LOOP_MARKER],
    ['.codex/config.toml', CODEX_CONFIG_STAMP]
  ]) {
    if (await isRealFile(targetDir, rel)) {
      try {
        if ((await readText(targetDir, rel)).includes(marker)) return true;
      } catch { /* unreadable -> not evidence */ }
    }
  }
  return false;
}

